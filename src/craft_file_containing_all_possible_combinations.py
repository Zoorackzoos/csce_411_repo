import datetime
import itertools


def craft_file_containing_all_possible_combinations(
        algorithm_name,
        list_of_quizes_that_satify_criteria,
        tab_amount=""
):
    """
    this writes a file that contains all of the possible combinations of
    what is inside list_of_quizes_that_satify_criteria.

    :param list_of_quizes_that_satify_criteria:
    :param tab_amount:
    :return:
    """
    print(tab_amount,"craft_file_containing_all_possible_combinations")
    tab_amount += "\t"

    export_directory_path = "../exported_combonation_of_quiz_files"
    current_time_var = str(datetime.datetime.now())[0:10] + "_"
    file_name_var = str(algorithm_name) + "_output"
    full_directory_path = export_directory_path + "/" + current_time_var + file_name_var + ".txt"

    with open(full_directory_path, "w") as file:
        file.write("This file was generated by \"craft_file_containing_all_possible_combinations\"\n")
        file.write(f"\tThe final set spat out by \"{algorithm_name}\" was:\n")

        for list_element in list_of_quizes_that_satify_criteria:
            file.write(f"\t\t{list_element}\n")

        file.write("\n")
        file.write("\tHere are all of the combinations:\n")

        combinations_list = itertools.combinations(
            list_of_quizes_that_satify_criteria,
            len(list_of_quizes_that_satify_criteria)
        )

        for combination in combinations_list:
            file.write(f"\t\t{combination}\n")
