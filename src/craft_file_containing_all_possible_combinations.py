import datetime
import itertools


def craft_file_containing_all_possible_combinations(
        algorithm_name,
        list_of_quizzes_that_satisfy_criteria,
        tab_amount=""
):
    """
    this writes a file that contains all the possible combinations of
    what is inside list_of_quizes_that_satify_criteria.

    this does not return anything.

    :param algorithm_name:
    :param list_of_quizzes_that_satisfy_criteria:
    :param tab_amount:
    :return:
    """
    print(tab_amount,"craft_file_containing_all_possible_combinations")
    tab_amount += "\t"

    export_directory_path = "../exported_combonation_of_quiz_files"
    current_time_var = str(datetime.datetime.now())[0:10] + "_"
    file_name_var = str(algorithm_name) + "_output"
    full_directory_path = export_directory_path + "/" + current_time_var + file_name_var + ".log"

    master_printing_string = ""

    with open(full_directory_path, "w") as file:
        master_printing_string += "This file was generated by \"craft_file_containing_all_possible_combinations\"\n"
        master_printing_string += f"\tThis is saved in a log file at {full_directory_path}\n"
        master_printing_string += F"\t\tI'm also printing this in the terminal.\n"
        master_printing_string += "\n"
        master_printing_string += f"\tThe final set spat out by \"{algorithm_name}\" was:\n"

        for list_element in list_of_quizzes_that_satisfy_criteria:
            master_printing_string += f"\t\t{list_element}\n"

        master_printing_string += "\n"
        master_printing_string += "\tHere are all the combinations:\n"

        combinations_list = itertools.combinations(
            list_of_quizzes_that_satisfy_criteria,
            len(list_of_quizzes_that_satisfy_criteria)
        )

        for combination in combinations_list:
            master_printing_string += f"\t\t{combination}\n"

        file.write(master_printing_string)

    print(master_printing_string)